-- MORROW CLOUD SCHEMA (PostgreSQL / Neon)
-- Run once in a NEW, empty Neon database using the Neon SQL Editor.
-- Do not run this script against the existing local Oracle database.

CREATE TABLE users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(100) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    role VARCHAR(10) NOT NULL DEFAULT 'USER',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_users_status CHECK (status IN ('ACTIVE', 'SUSPENDED', 'CLOSED')),
    CONSTRAINT ck_users_role CHECK (role IN ('USER', 'ADMIN'))
);

CREATE TABLE wallets (
    wallet_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id),
    currency_code CHAR(3) NOT NULL DEFAULT 'INR',
    balance NUMERIC(14,2) NOT NULL DEFAULT 0.00,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_wallet_balance CHECK (balance >= 0),
    CONSTRAINT uk_user_currency UNIQUE (user_id, currency_code)
);

CREATE TABLE transactions (
    transaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference_code VARCHAR(40) NOT NULL UNIQUE,
    transaction_type VARCHAR(20) NOT NULL,
    sender_wallet_id BIGINT REFERENCES wallets(wallet_id),
    receiver_wallet_id BIGINT REFERENCES wallets(wallet_id),
    amount NUMERIC(14,2) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'COMPLETED',
    description VARCHAR(250),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_transaction_amount CHECK (amount > 0),
    CONSTRAINT ck_transaction_type CHECK (transaction_type IN ('TOP_UP', 'TRANSFER', 'PAYMENT', 'REFUND')),
    CONSTRAINT ck_transaction_status CHECK (status IN ('PENDING', 'COMPLETED', 'FAILED', 'REVERSED'))
);

CREATE TABLE ledger (
    ledger_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wallet_id BIGINT NOT NULL REFERENCES wallets(wallet_id),
    transaction_id BIGINT NOT NULL REFERENCES transactions(transaction_id),
    entry_type VARCHAR(10) NOT NULL,
    amount NUMERIC(14,2) NOT NULL,
    balance_after NUMERIC(14,2) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_ledger_type CHECK (entry_type IN ('CREDIT', 'DEBIT')),
    CONSTRAINT ck_ledger_amount CHECK (amount > 0),
    CONSTRAINT ck_ledger_balance CHECK (balance_after >= 0)
);

CREATE INDEX ix_transactions_created ON transactions(created_at DESC);
CREATE INDEX ix_transactions_sender ON transactions(sender_wallet_id);
CREATE INDEX ix_transactions_receiver ON transactions(receiver_wallet_id);
CREATE INDEX ix_ledger_wallet_date ON ledger(wallet_id, created_at);

-- Verify the four tables.
SELECT table_name
FROM information_schema.tables
WHERE table_schema = 'public'
  AND table_name IN ('users', 'wallets', 'transactions', 'ledger')
ORDER BY table_name;
