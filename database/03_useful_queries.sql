-- Basic SQL queries for learning and PAT demonstration.

-- List users (never select PASSWORD_HASH for display in the website).
SELECT USER_ID, FULL_NAME, EMAIL, STATUS, CREATED_AT
FROM USERS
ORDER BY CREATED_AT DESC;

-- View wallet balance.
SELECT W.WALLET_ID, U.FULL_NAME, W.CURRENCY_CODE, W.BALANCE
FROM WALLETS W
JOIN USERS U ON U.USER_ID = W.USER_ID
ORDER BY W.WALLET_ID;

-- Transaction history with sender/receiver wallet identifiers.
SELECT TRANSACTION_ID, REFERENCE_CODE, TRANSACTION_TYPE,
       SENDER_WALLET_ID, RECEIVER_WALLET_ID, AMOUNT, STATUS, CREATED_AT
FROM TRANSACTIONS
ORDER BY CREATED_AT DESC;

-- Ledger entries for an individual wallet (replace 1 with a real wallet id).
SELECT LEDGER_ID, TRANSACTION_ID, ENTRY_TYPE, AMOUNT, BALANCE_AFTER, CREATED_AT
FROM LEDGER
WHERE WALLET_ID = 1
ORDER BY CREATED_AT DESC;
