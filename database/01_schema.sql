-- Morrow Wallet schema compatible with Oracle Database XE 11g. Run once as MORROW_APP.
-- Oracle 11g has no identity columns, so sequences and triggers generate primary keys.

CREATE TABLE USERS (
    USER_ID       NUMBER PRIMARY KEY,
    FULL_NAME     VARCHAR2(100) NOT NULL,
    EMAIL         VARCHAR2(255) NOT NULL,
    PASSWORD_HASH VARCHAR2(255) NOT NULL,
    STATUS        VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UK_MW_USERS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_MW_USERS_STATUS CHECK (STATUS IN ('ACTIVE', 'SUSPENDED', 'CLOSED'))
);

CREATE TABLE WALLETS (
    WALLET_ID     NUMBER PRIMARY KEY,
    USER_ID       NUMBER NOT NULL,
    CURRENCY_CODE CHAR(3) DEFAULT 'INR' NOT NULL,
    BALANCE       NUMBER(14,2) DEFAULT 0 NOT NULL,
    CREATED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_MW_WALLET_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID),
    CONSTRAINT CK_MW_WALLET_BALANCE CHECK (BALANCE >= 0),
    CONSTRAINT UK_MW_USER_CURRENCY UNIQUE (USER_ID, CURRENCY_CODE)
);

CREATE TABLE TRANSACTIONS (
    TRANSACTION_ID   NUMBER PRIMARY KEY,
    REFERENCE_CODE   VARCHAR2(40) NOT NULL,
    TRANSACTION_TYPE VARCHAR2(20) NOT NULL,
    SENDER_WALLET_ID NUMBER,
    RECEIVER_WALLET_ID NUMBER,
    AMOUNT           NUMBER(14,2) NOT NULL,
    STATUS           VARCHAR2(20) DEFAULT 'COMPLETED' NOT NULL,
    DESCRIPTION      VARCHAR2(250),
    CREATED_AT       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UK_MW_TX_REFERENCE UNIQUE (REFERENCE_CODE),
    CONSTRAINT FK_MW_TX_SENDER FOREIGN KEY (SENDER_WALLET_ID) REFERENCES WALLETS(WALLET_ID),
    CONSTRAINT FK_MW_TX_RECEIVER FOREIGN KEY (RECEIVER_WALLET_ID) REFERENCES WALLETS(WALLET_ID),
    CONSTRAINT CK_MW_TX_AMOUNT CHECK (AMOUNT > 0),
    CONSTRAINT CK_MW_TX_TYPE CHECK (TRANSACTION_TYPE IN ('TOP_UP', 'TRANSFER', 'PAYMENT', 'REFUND')),
    CONSTRAINT CK_MW_TX_STATUS CHECK (STATUS IN ('PENDING', 'COMPLETED', 'FAILED', 'REVERSED'))
);

CREATE TABLE LEDGER (
    LEDGER_ID      NUMBER PRIMARY KEY,
    WALLET_ID      NUMBER NOT NULL,
    TRANSACTION_ID NUMBER NOT NULL,
    ENTRY_TYPE     VARCHAR2(10) NOT NULL,
    AMOUNT         NUMBER(14,2) NOT NULL,
    BALANCE_AFTER  NUMBER(14,2) NOT NULL,
    CREATED_AT     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_MW_LEDGER_WALLET FOREIGN KEY (WALLET_ID) REFERENCES WALLETS(WALLET_ID),
    CONSTRAINT FK_MW_LEDGER_TX FOREIGN KEY (TRANSACTION_ID) REFERENCES TRANSACTIONS(TRANSACTION_ID),
    CONSTRAINT CK_MW_LEDGER_TYPE CHECK (ENTRY_TYPE IN ('CREDIT', 'DEBIT')),
    CONSTRAINT CK_MW_LEDGER_AMOUNT CHECK (AMOUNT > 0),
    CONSTRAINT CK_MW_LEDGER_BALANCE CHECK (BALANCE_AFTER >= 0)
);

CREATE INDEX IX_MW_TX_CREATED ON TRANSACTIONS(CREATED_AT);
CREATE INDEX IX_MW_TX_SENDER ON TRANSACTIONS(SENDER_WALLET_ID);
CREATE INDEX IX_MW_TX_RECEIVER ON TRANSACTIONS(RECEIVER_WALLET_ID);
CREATE INDEX IX_MW_LEDGER_WALLET_DATE ON LEDGER(WALLET_ID, CREATED_AT);

-- Primary-key generators for Oracle 11g (identity columns are not available).
CREATE SEQUENCE MW_USERS_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE MW_WALLETS_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE MW_TRANSACTIONS_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE MW_WALLET_LEDGER_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE OR REPLACE TRIGGER BI_MW_USERS
BEFORE INSERT ON USERS
FOR EACH ROW
WHEN (NEW.USER_ID IS NULL)
BEGIN
    SELECT MW_USERS_SEQ.NEXTVAL INTO :NEW.USER_ID FROM DUAL;
END;
/

CREATE OR REPLACE TRIGGER BI_MW_WALLETS
BEFORE INSERT ON WALLETS
FOR EACH ROW
WHEN (NEW.WALLET_ID IS NULL)
BEGIN
    SELECT MW_WALLETS_SEQ.NEXTVAL INTO :NEW.WALLET_ID FROM DUAL;
END;
/

CREATE OR REPLACE TRIGGER BI_MW_TRANSACTIONS
BEFORE INSERT ON TRANSACTIONS
FOR EACH ROW
WHEN (NEW.TRANSACTION_ID IS NULL)
BEGIN
    SELECT MW_TRANSACTIONS_SEQ.NEXTVAL INTO :NEW.TRANSACTION_ID FROM DUAL;
END;
/

CREATE OR REPLACE TRIGGER BI_MW_WALLET_LEDGER
BEFORE INSERT ON LEDGER
FOR EACH ROW
WHEN (NEW.LEDGER_ID IS NULL)
BEGIN
    SELECT MW_WALLET_LEDGER_SEQ.NEXTVAL INTO :NEW.LEDGER_ID FROM DUAL;
END;
/
